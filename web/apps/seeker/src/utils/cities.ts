export const CITY_COLUMNS: CityOption[] = RAW.map(([p, cs]) => ({
  text: p,
  value: p,
  children: cs.map((c) => ({ text: c, value: c })),
}))

/** 根据城市名找省份（回显选择器） */
export function provinceOf(city: string): string | undefined {
  return RAW.find(([, cs]) => cs.includes(city))?.[0]
}
